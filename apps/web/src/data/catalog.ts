export function getProductById(id: string) {
  return PRODUCTS.find((p) => p.id === id) || null;
}

export function filterProducts(filters: ProductFilters = {}) {
  let list = [...PRODUCTS];
  const {
    sport,
    category,
    brand,
    minPrice,
    maxPrice,
    q,
    badge,
    featured,
    size,
    inStock,
    onSale,
    sort = 'featured',
  } = filters;

  if (sport) list = list.filter((p) => p.sport === sport);
  if (category) {
    const cats = Array.isArray(category) ? category : [category];
    if (cats.length) list = list.filter((p) => cats.includes(p.category));
  }
  if (brand) {
    const brands = Array.isArray(brand) ? brand : [brand];
    if (brands.length) list = list.filter((p) => brands.includes(p.brand));
  }
  if (size) {
    const sizes = Array.isArray(size) ? size : [size];
    if (sizes.length) {
      list = list.filter((p) => (p.sizes || []).some((s) => sizes.includes(String(s))));
    }
  }
  if (badge) list = list.filter((p) => p.badge === badge);
  if (onSale === true || onSale === 'true') {
    list = list.filter((p) => p.originalPrice || p.badge === 'sale');
  }
  if (featured === true || featured === 'true') list = list.filter((p) => p.featured);
  if (inStock === true || inStock === 'true') list = list.filter((p) => (p.stock || 0) > 0);
  if (minPrice != null && minPrice !== '') list = list.filter((p) => p.price >= Number(minPrice));
  if (maxPrice != null && maxPrice !== '') list = list.filter((p) => p.price <= Number(maxPrice));
  if (q) {
    const term = String(q).toLowerCase();
    list = list.filter(
      (p) =>
        p.name.toLowerCase().includes(term) ||
        p.brand.toLowerCase().includes(term) ||
        p.category.toLowerCase().includes(term) ||
        p.sport.toLowerCase().includes(term) ||
        (p.description && p.description.toLowerCase().includes(term))
    );
  }

  switch (sort) {
    case 'price-low':
      list.sort((a, b) => a.price - b.price);
      break;
    case 'price-high':
      list.sort((a, b) => b.price - a.price);
      break;
    case 'rating':
      list.sort((a, b) => b.rating - a.rating);
      break;
    case 'newest':
      list.sort((a, b) => Number(b.badge === 'new') - Number(a.badge === 'new'));
      break;
    case 'name':
      list.sort((a, b) => a.name.localeCompare(b.name));
      break;
    default:
      list.sort((a, b) => (b.featured ? 1 : 0) - (a.featured ? 1 : 0) || b.rating - a.rating);
  }

  return list;
}

export function getRelatedProducts(product: Product, limit = 4) {
  return PRODUCTS.filter(
    (p) => p.id !== product.id && (p.sport === product.sport || p.category === product.category)
  )
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
}

export function getBrands(sport?: string) {
  const set = new Set(
    PRODUCTS.filter((p) => !sport || p.sport === sport).map((p) => p.brand)
  );
  return [...set].sort();
}

export function getCategoriesForSport(sport?: string) {
  const set = new Set(
    PRODUCTS.filter((p) => !sport || p.sport === sport).map((p) => p.category)
  );
  return [...set];
}
